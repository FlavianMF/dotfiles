#!/bin/bash
# Installs Obsidian (AppImage) into ~/.local/opt/obsidian, pinned by sha256. No sudo needed.
# Also creates the ~/.local/bin/obsidian launcher, the desktop entry, and registers the vault
# (~/obsidian_vault, or $OBSIDIAN_VAULT) in ~/.config/obsidian/obsidian.json when the app has no config yet.
# Usage: obsidian/install.sh [--dry-run] [--update [x.y.z]]
#   --update  look up the release (latest, or x.y.z) on GitHub and rewrite obsidian/VERSION and
#             obsidian/SHA256 with the digest GitHub publishes, without installing.
#             Review the diff, then run the installer again.
# The pin is the pair obsidian/VERSION + obsidian/SHA256 (sha256 of the amd64 AppImage).
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="obsidianmd/obsidian-releases"
DEST="${OBSIDIAN_HOME:-$HOME/.local/opt/obsidian}"
BIN="${OBSIDIAN_BIN:-$HOME/.local/bin/obsidian}"
DESKTOP="${OBSIDIAN_DESKTOP:-$HOME/.local/share/applications/obsidian.desktop}"
ICON_DIR="${OBSIDIAN_ICON_DIR:-$HOME/.local/share/icons/hicolor/512x512/apps}"
VAULT="${OBSIDIAN_VAULT:-$HOME/obsidian_vault}"
APP_CONFIG="${OBSIDIAN_CONFIG:-${XDG_CONFIG_HOME:-$HOME/.config}/obsidian/obsidian.json}"
DRY_RUN=0
UPDATE=0
UPDATE_VERSION=""
while [[ $# -gt 0 ]]; do
    case "$1" in
        --dry-run) DRY_RUN=1 ;;
        --update)
            UPDATE=1
            if [[ "${2:-}" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
                UPDATE_VERSION="$2"
                shift
            fi
            ;;
        *)
            echo "Unknown option: $1" >&2
            exit 2
            ;;
    esac
    shift
done

[[ "$(uname -m)" == x86_64 ]] || { echo "obsidian/install.sh supports x86_64 only (this is $(uname -m))" >&2; exit 1; }

if [[ $UPDATE -eq 1 ]]; then
    if [[ $DRY_RUN -eq 1 ]]; then
        echo "[dry-run] look up ${UPDATE_VERSION:-latest} on github.com/$REPO and write $ROOT/VERSION and $ROOT/SHA256"
        exit 0
    fi
    api="https://api.github.com/repos/$REPO/releases/latest"
    [[ -n "$UPDATE_VERSION" ]] && api="https://api.github.com/repos/$REPO/releases/tags/v$UPDATE_VERSION"
    json="$(curl -fsSL "$api")"
    tag="$(jq -r '.tag_name' <<< "$json")"
    version="${tag#v}"
    digest="$(jq -r --arg n "Obsidian-$version.AppImage" '.assets[] | select(.name == $n) | .digest' <<< "$json")"
    [[ "$digest" == sha256:* ]] || { echo "No sha256 digest for Obsidian-$version.AppImage in release $tag" >&2; exit 1; }
    printf '%s\n' "$version" > "$ROOT/VERSION"
    printf '%s  Obsidian-%s.AppImage\n' "${digest#sha256:}" "$version" > "$ROOT/SHA256"
    echo "Pinned Obsidian $version (${digest#sha256:}). Review git diff, then rerun obsidian/install.sh."
    exit 0
fi

[[ -r "$ROOT/VERSION" && -r "$ROOT/SHA256" ]] || { echo "Missing $ROOT/VERSION or SHA256; run obsidian/install.sh --update" >&2; exit 1; }
VERSION="$(tr -d '[:space:]' < "$ROOT/VERSION")"
NAME="Obsidian-$VERSION.AppImage"
EXPECTED="$(awk -v n="$NAME" '$2 == n {print $1}' "$ROOT/SHA256")"
[[ -n "$EXPECTED" ]] || { echo "$ROOT/SHA256 has no entry for $NAME" >&2; exit 1; }
URL="https://github.com/$REPO/releases/download/v$VERSION/$NAME"
APPIMAGE="$DEST/$NAME"

# Launcher: the AppImage runtime needs libfuse2 (libfuse2t64 on Ubuntu 24.04+); without it, extract and run.
# Electron's sandbox needs unprivileged user namespaces (an AppImage can't ship a setuid chrome-sandbox),
# so --no-sandbox is added only where they are unavailable.
launcher() {
    cat << EOF
#!/bin/bash
# Generated by dotfiles obsidian/install.sh. Do not edit.
app="$DEST/current.AppImage"
args=()
/sbin/ldconfig -p 2> /dev/null | grep -q 'libfuse\.so\.2' || export APPIMAGE_EXTRACT_AND_RUN=1
unshare -U true 2> /dev/null || args+=(--no-sandbox)
exec "\$app" "\${args[@]}" "\$@"
EOF
}

desktop_entry() {
    cat << EOF
[Desktop Entry]
Name=Obsidian
Comment=Knowledge base
Exec=$BIN %U
Terminal=false
Type=Application
Icon=obsidian
StartupWMClass=obsidian
MimeType=x-scheme-handler/obsidian;
Categories=Office;
EOF
}

if [[ $DRY_RUN -eq 1 ]]; then
    echo "[dry-run] download $URL, verify sha256 $EXPECTED"
    echo "[dry-run] install $APPIMAGE (+ $DEST/current.AppImage link), launcher $BIN, desktop entry $DESKTOP"
    if [[ -d "$VAULT" && ! -e "$APP_CONFIG" ]]; then echo "[dry-run] register vault $VAULT in $APP_CONFIG"; fi
    exit 0
fi

if [[ -x "$APPIMAGE" ]] && [[ "$(sha256sum "$APPIMAGE" | cut -d' ' -f1)" == "$EXPECTED" ]]; then
    echo "Obsidian $VERSION already installed"
else
    echo "Installing Obsidian $VERSION..."
    tmp="$(mktemp -d)"
    trap 'rm -rf "$tmp"' EXIT
    curl -fsSL -o "$tmp/$NAME" "$URL" || { echo "Download failed: $URL" >&2; exit 1; }
    actual="$(sha256sum "$tmp/$NAME" | cut -d' ' -f1)"
    if [[ "$actual" != "$EXPECTED" ]]; then
        echo "sha256 mismatch for $NAME" >&2
        echo "  pinned: $EXPECTED" >&2
        echo "  actual: $actual" >&2
        exit 1
    fi
    mkdir -p "$DEST"
    install -m 755 "$tmp/$NAME" "$APPIMAGE"
fi
ln -sfn "$NAME" "$DEST/current.AppImage"
# Drop AppImages from older pins.
find "$DEST" -maxdepth 1 -name 'Obsidian-*.AppImage' ! -name "$NAME" -delete

mkdir -p "$(dirname "$BIN")" "$(dirname "$DESKTOP")" "$ICON_DIR"
launcher > "$BIN"
chmod 755 "$BIN"
desktop_entry > "$DESKTOP"

# Icon: pull it out of the AppImage (squashfs) without running the app.
icon_src="usr/share/icons/hicolor/512x512/apps/obsidian.png"
if [[ ! -s "$ICON_DIR/obsidian.png" ]]; then
    ext="$(mktemp -d)"
    if (cd "$ext" && APPIMAGE_EXTRACT_AND_RUN=1 "$APPIMAGE" --appimage-extract "$icon_src" > /dev/null 2>&1) \
        && [[ -s "$ext/squashfs-root/$icon_src" ]]; then
        cp "$ext/squashfs-root/$icon_src" "$ICON_DIR/obsidian.png"
    else
        echo "WARNING: could not extract the Obsidian icon; the desktop entry will use a generic one." >&2
    fi
    rm -rf "$ext"
fi
if command -v update-desktop-database > /dev/null; then update-desktop-database "$(dirname "$DESKTOP")" 2> /dev/null || true; fi

# Register the vault so the first launch opens it instead of the vault picker. Only when Obsidian has no
# config yet: after that the app owns obsidian.json (vault list, window state) and we leave it alone.
if [[ -d "$VAULT" && ! -e "$APP_CONFIG" ]]; then
    vault_id="$(od -An -N8 -tx1 /dev/urandom | tr -d ' \n')"
    mkdir -p "$(dirname "$APP_CONFIG")"
    jq -n --arg id "$vault_id" --arg path "$VAULT" --argjson ts "$(($(date +%s) * 1000))" \
        '{vaults: {($id): {path: $path, ts: $ts, open: true}}}' > "$APP_CONFIG"
    echo "Registered vault $VAULT in $APP_CONFIG"
fi

case ":$PATH:" in *":$(dirname "$BIN"):"*) ;; *) echo "NOTE: $(dirname "$BIN") is not in PATH" >&2 ;; esac
echo "Obsidian $VERSION installed. Launch with: obsidian"
